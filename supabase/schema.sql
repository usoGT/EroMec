  worked_half smallint not null check (worked_half in (0, 1, 2)),
  is_system   boolean not null default false,
  sort_order  integer not null default 100
);

-- ───────────────────────── Çalışanlar ─────────────────────────

create table public.employees (
  id                   bigint generated by default as identity primary key,
  employee_no          text   not null unique,
  full_name            text   not null check (length(trim(full_name)) > 0),
  position             text   not null check (length(trim(position)) > 0),
  monthly_salary_kurus bigint not null default 0 check (monthly_salary_kurus >= 0),
  overtime_rate_kurus  bigint not null default 0 check (overtime_rate_kurus >= 0),
  start_date           date,
  status               text   not null default 'active' check (status in ('active', 'left')),
  phone                text   not null default '',
  notes                text   not null default '',
  site_id              bigint references public.sites(id) on delete set null,
  national_id          text   not null default '',
  iban                 text   not null default '',
  bank_name            text   not null default '',
  birth_date           date,
  address              text   not null default '',
  blood_type           text   not null default '',
  emergency_name       text   not null default '',
  emergency_phone      text   not null default '',
  sgk_no               text   not null default '',
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create unique index ux_employees_national_id on public.employees (national_id) where national_id <> '';
create index ix_employees_site on public.employees (site_id);

-- ───────────────────────── Mesai, gider, puantaj, bordro, rapor ─────────────────────────

create table public.overtime_records (
  id                bigint generated by default as identity primary key,
  employee_id       bigint  not null references public.employees(id) on delete restrict,
  site_id           bigint  references public.sites(id) on delete restrict,
  date              date    not null,
  start_time        text    not null,
  end_time          text    not null,
  break_minutes     integer not null default 0 check (break_minutes >= 0),
  worked_minutes    integer not null check (worked_minutes > 0),
  hourly_rate_kurus bigint  not null check (hourly_rate_kurus >= 0),
  total_kurus       bigint  not null check (total_kurus >= 0),
  description       text    not null default '',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (employee_id, date, start_time)
);
create index ix_overtime_date on public.overtime_records (date);
create index ix_overtime_site on public.overtime_records (site_id);

create table public.expenses (
  id            bigint generated by default as identity primary key,
  date          date    not null,
  name          text    not null,
  category_id   bigint  not null references public.expense_categories(id) on delete restrict,
  amount_kurus  bigint  not null check (amount_kurus >= 0),
  is_paid       boolean not null default false,
  description   text    not null default '',
  employee_id   bigint  references public.employees(id) on delete restrict,
  salary_period text,
  site_id       bigint  references public.sites(id) on delete restrict,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  check (salary_period is null or employee_id is not null)
);
-- Bordro bir çalışan/ay için maaş + mesai olmak üzere iki gider açar; aynı kategoriden ikincisi açılamaz.
create unique index ux_salary_payment on public.expenses (employee_id, salary_period, category_id) where salary_period is not null;
create index ix_expenses_date on public.expenses (date);
create index ix_expenses_category on public.expenses (category_id);
create index ix_expenses_site on public.expenses (site_id);

create table public.attendance (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  date        date   not null,
  status      text   not null references public.attendance_statuses(code) on delete restrict on update cascade,
  site_id     bigint references public.sites(id) on delete restrict,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (employee_id, date)
);
create index ix_attendance_date on public.attendance (date);
create index ix_attendance_site on public.attendance (site_id);
create index ix_attendance_status on public.attendance (status);

create table public.payrolls (
  id                   bigint generated by default as identity primary key,
  employee_id          bigint  not null references public.employees(id) on delete restrict,
  site_id              bigint  references public.sites(id) on delete restrict,
  period               text    not null,
  expense_id           bigint  not null references public.expenses(id) on delete cascade,
  overtime_expense_id  bigint  references public.expenses(id) on delete set null,
  paid_half_days       integer not null check (paid_half_days between 0 and 62),
  monthly_salary_kurus bigint  not null,
  normal_kurus         bigint  not null check (normal_kurus >= 0),
  overtime_minutes     integer not null default 0,
  overtime_kurus       bigint  not null check (overtime_kurus >= 0),
  total_kurus          bigint  not null check (total_kurus >= 0),
  official_kurus       bigint  not null check (official_kurus >= 0),
  cash_kurus           bigint  not null check (cash_kurus >= 0),
  daily_min_wage_kurus bigint  not null default 0,
  created_at           timestamptz not null default now(),
  unique (employee_id, period)
);
create index ix_payrolls_site on public.payrolls (site_id);

create table public.daily_reports (
  id         bigint generated by default as identity primary key,
  date       date   not null,
  site_id    bigint references public.sites(id) on delete restrict,
  weather    text   not null default '',
  work_done  text   not null default '',
  notes      text   not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index ux_daily_report_date_site on public.daily_reports (date, coalesce(site_id, 0));

create table public.activity_log (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id    uuid default auth.uid() references public.profiles(id) on delete set null,
  site_id    bigint references public.sites(id) on delete set null,
  entity     text not null,
  entity_id  bigint,
  action     text not null,
  summary    text not null
);
create index ix_activity_created on public.activity_log (created_at desc);

