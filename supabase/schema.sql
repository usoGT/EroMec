-- EroMec çevrimiçi veritabanı (Supabase / Postgres)
-- Supabase panelinde: SQL Editor → New query → bu dosyanın tamamını yapıştır → Run.
-- Masaüstündeki SQLite şemasının (sürüm 6) karşılığıdır; para tutarları yine kuruş (bigint),
-- tarihler 'yyyy-mm-dd' biçiminde date tipindedir.
--
-- Yetki kuralı:
--   admin  (ana firma)     → her şeyi görür ve yönetir
--   chief  (şantiye şefi)  → yalnızca atandığı şantiyelerin her şeyini görür ve yönetir (maaş, T.C., IBAN dahil)
-- Kim hangi şantiyede: site_members tablosu. Bu tabloyu yalnızca admin değiştirebilir.

-- ───────────────────────── Kullanıcılar ─────────────────────────

create table public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text not null,
  full_name  text not null default '',
  role       text not null default 'chief' check (role in ('admin', 'chief')),
  created_at timestamptz not null default now()
);

-- Supabase'de yeni kullanıcı açılınca (davetle) otomatik profil oluşur; varsayılan rol şantiye şefi.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, coalesce(new.email, ''), coalesce(new.raw_user_meta_data->>'full_name', ''));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ───────────────────────── Firma ve şantiye ─────────────────────────

create table public.companies (
  id         bigint generated by default as identity primary key,
  name       text not null check (length(trim(name)) > 0),
  tax_office text not null default '',
  tax_no     text not null default '',
  phone      text not null default '',
  address    text not null default '',
  notes      text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index ux_companies_name on public.companies (lower(name));

create table public.sites (
  id         bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  name       text not null check (length(trim(name)) > 0),
  address    text not null default '',
  start_date date,
  end_date   date,
  status     text not null default 'active' check (status in ('active', 'completed')),
  notes      text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, name)
);

create table public.site_members (
  user_id    uuid   not null references public.profiles(id) on delete cascade,
  site_id    bigint not null references public.sites(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, site_id)
);
create index ix_site_members_site on public.site_members (site_id);

-- ───────────────────────── Yetki yardımcıları ─────────────────────────
-- security definer: RLS içinde çağrıldıklarında kendi tablolarının RLS'ine takılmazlar.

create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Şantiyesi boş (genel) kayıtlar yalnızca admine açıktır.
create function public.can_access_site(sid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin()
      or (sid is not null and exists (
            select 1 from public.site_members where user_id = auth.uid() and site_id = sid));
$$;

