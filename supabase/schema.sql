-- Profiller: herkes kendini görür; admin herkesi görür ve rol verir.
create policy profiles_read  on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy profiles_admin on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy profiles_admin_delete on public.profiles for delete to authenticated using (public.is_admin());

-- Şantiye atamaları: şef kendi atamalarını görür, yalnızca admin değiştirir.
create policy site_members_read  on public.site_members for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy site_members_admin on public.site_members for all    to authenticated using (public.is_admin()) with check (public.is_admin());

-- Şantiyeler: şef kendi şantiyesini görür ve bilgilerini düzenler; açma/silme admin.
create policy sites_read   on public.sites for select to authenticated using (public.can_access_site(id));
create policy sites_update on public.sites for update to authenticated using (public.can_access_site(id)) with check (public.can_access_site(id));
create policy sites_insert on public.sites for insert to authenticated with check (public.is_admin());
create policy sites_delete on public.sites for delete to authenticated using (public.is_admin());

-- Firmalar: şef yalnızca kendi şantiyesinin bağlı olduğu firmayı görür; yönetim admin.
create policy companies_read on public.companies for select to authenticated using (
  public.is_admin() or exists (select 1 from public.sites s where s.company_id = companies.id and public.can_access_site(s.id)));
create policy companies_admin on public.companies for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Ortak listeler: herkes okur, admin değiştirir.
create policy settings_read  on public.settings for select to authenticated using (true);
create policy settings_admin on public.settings for all    to authenticated using (public.is_admin()) with check (public.is_admin());
create policy categories_read  on public.expense_categories for select to authenticated using (true);
create policy categories_admin on public.expense_categories for all    to authenticated using (public.is_admin()) with check (public.is_admin());
create policy statuses_read  on public.attendance_statuses for select to authenticated using (true);
create policy statuses_admin on public.attendance_statuses for all    to authenticated using (public.is_admin()) with check (public.is_admin());

