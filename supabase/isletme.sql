-- ───────────── İşletme açma, üye ekleme/çıkarma ─────────────
create or replace function public.workspace_create(ws_name text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare ws bigint; nm text := trim(ws_name);
begin
  if auth.uid() is null then raise exception 'Giriş gerekli' using errcode = '42501'; end if;
  if length(nm) < 2 then raise exception 'İşletme adını yazın.' using errcode = '22023'; end if;
  if public.my_workspace() is not null then raise exception 'Zaten bir işletmedesiniz.' using errcode = '42501'; end if;
  insert into public.workspaces (name, created_by) values (nm, auth.uid()) returning id into ws;
  update public.profiles set workspace_id = ws, workspace_role = 'owner' where id = auth.uid();
  insert into public.settings (workspace_id, key, value) select ws, key, value from public.template_settings;
  insert into public.settings (workspace_id, key, value) values (ws, 'companyName', nm)
    on conflict (workspace_id, key) do update set value = excluded.value;
  insert into public.expense_categories (workspace_id, name, kind, is_system, sort_order)
    select ws, name, kind, is_system, sort_order from public.template_categories;
  insert into public.attendance_statuses (workspace_id, code, short, label, color, paid_half, worked_half, is_system, sort_order)
    select ws, code, short, label, color, paid_half, worked_half, is_system, sort_order from public.template_statuses;
  insert into public.companies (workspace_id, name) values (ws, nm);
  delete from public.workspace_invites where lower(email) = lower((select email from public.profiles where id = auth.uid()));
  return jsonb_build_object('id', ws, 'name', nm);
end $$;

create or replace function public.workspace_members() returns table (user_id uuid, email text, full_name text, role text, pending boolean)
language sql stable security definer set search_path = public as $$
  select p.id, p.email, p.full_name, p.workspace_role, false from public.profiles p
    where p.workspace_id = public.my_workspace() and public.my_workspace() is not null
  union all
  select null, i.email, '', 'member', true from public.workspace_invites i where i.workspace_id = public.my_workspace()
  order by 5, 4 desc, 3, 2;
$$;

-- İşletme sahibi üye ekler: kayıtlıysa hemen katılır, değilse kayıt olunca katılır.
create or replace function public.workspace_add_member(member_email text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare p public.profiles; ws bigint := public.my_workspace(); mail text := lower(trim(member_email));
begin
  if auth.uid() is null or ws is null or not public.is_admin() then
    raise exception 'Üye eklemeyi yalnızca işletme sahibi yapabilir.' using errcode = '42501';
  end if;
  if mail !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Geçerli bir e-posta adresi girin.' using errcode = '22023'; end if;
  select * into p from public.profiles where lower(email) = mail;
  if p.id is null then
    insert into public.workspace_invites (email, workspace_id) values (mail, ws) on conflict do nothing;
    return jsonb_build_object('email', mail, 'pending', true);
  end if;
  if p.workspace_id = ws then return jsonb_build_object('email', p.email, 'pending', false); end if;
  if p.workspace_id is not null then
    raise exception 'Bu kişi başka bir işletmede. Önce oradan ayrılması gerekir.' using errcode = '42501';
  end if;
  update public.profiles set workspace_id = ws, workspace_role = 'member' where id = p.id;
  return jsonb_build_object('email', p.email, 'fullName', p.full_name, 'pending', false);
end $$;

-- Üyeyi çıkarır (sahip) ya da üye kendisi ayrılır. Sahip ayrılamaz.
create or replace function public.workspace_remove_member(member_id uuid, member_email text default null) returns void
language plpgsql security definer set search_path = public as $$
declare ws bigint := public.my_workspace(); target public.profiles;
begin
  if auth.uid() is null or ws is null then raise exception 'Giriş gerekli' using errcode = '42501'; end if;
  if member_id is null then
    if not public.is_admin() then raise exception 'Bu işlem için yetkiniz yok.' using errcode = '42501'; end if;
    delete from public.workspace_invites where workspace_id = ws and lower(email) = lower(trim(member_email));
    return;
  end if;
  select * into target from public.profiles where id = member_id and workspace_id = ws;
  if target.id is null then raise exception 'Bu kişi işletmenizde değil.' using errcode = 'P0002'; end if;
  if target.workspace_role = 'owner' then raise exception 'İşletme sahibi işletmeden çıkarılamaz.' using errcode = '42501'; end if;
  if not (member_id = auth.uid() or public.is_admin()) then raise exception 'Bu işlem için yetkiniz yok.' using errcode = '42501'; end if;
  delete from public.site_members m using public.sites s where m.site_id = s.id and s.workspace_id = ws and m.user_id = member_id;
  update public.profiles set workspace_id = null, workspace_role = 'member' where id = member_id;
end $$;

-- Yeni kayıt: davet varsa işletmeye katılır.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare ws bigint;
begin
  select workspace_id into ws from public.workspace_invites where lower(email) = lower(coalesce(new.email, '')) order by created_at limit 1;
  insert into public.profiles (id, email, full_name, workspace_id, workspace_role)
  values (new.id, coalesce(new.email, ''), coalesce(new.raw_user_meta_data->>'full_name', ''), ws, 'member');
  if ws is not null then delete from public.workspace_invites where lower(email) = lower(coalesce(new.email, '')); end if;
  return new;
end $$;

