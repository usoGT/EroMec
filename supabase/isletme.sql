-- Satırlar işletme bilgisi olmadan gönderilir (cihazda tek işletme vardır); sunucu ekler.
create or replace function public.apply_changes(changes jsonb) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare c jsonb; t record; cols text; sets text; target text; n_del int := 0; n_up int := 0;
begin
  if auth.uid() is null then raise exception 'Giriş gerekli' using errcode = '42501'; end if;
  if public.my_workspace() is null then raise exception 'Önce bir işletme açın ya da bir işletmeye katılın.' using errcode = '42501'; end if;
  set constraints all deferred;
  for t in select * from public.sync_tables() order by ord loop
    target := case when t.tbl in ('settings', 'attendance_statuses') then format('workspace_id, %I', t.pk) else format('%I', t.pk) end;
    for c in select value from jsonb_array_elements(coalesce(changes->'upserts', '[]'::jsonb)) where value->>'t' = t.tbl loop
      select string_agg(format('%I', k), ', '), string_agg(format('%I = excluded.%I', k, k), ', ') filter (where k <> t.pk)
        into cols, sets
        from jsonb_object_keys(c->'row') k
        where k not in ('workspace_id', '_changed_at')
          and exists (select 1 from information_schema.columns ic where ic.table_schema = 'public' and ic.table_name = t.tbl and ic.column_name = k);
      if cols is null then continue; end if;
      execute format('insert into public.%I (%s) select %s from jsonb_populate_record(null::public.%I, $1) on conflict (%s) do %s',
                     t.tbl, cols, cols, t.tbl, target, case when sets is null then 'nothing' else 'update set ' || sets end)
        using c->'row';
      n_up := n_up + 1;
    end loop;
  end loop;
  for t in select * from public.sync_tables() order by ord desc loop
    for c in select value from jsonb_array_elements(coalesce(changes->'deletes', '[]'::jsonb)) where value->>'t' = t.tbl loop
      execute format('delete from public.%I where %I::text = $1 and workspace_id = public.my_workspace()', t.tbl, t.pk) using c->>'pk';
      n_del := n_del + 1;
    end loop;
  end loop;
  if (select count(*) from jsonb_array_elements(coalesce(changes->'deletes', '[]'::jsonb) || coalesce(changes->'upserts', '[]'::jsonb)) e
      where not exists (select 1 from public.sync_tables() s where s.tbl = e->>'t')) > 0 then
    raise exception 'Bilinmeyen tablo' using errcode = '22023';
  end if;
  return jsonb_build_object('deleted', n_del, 'upserted', n_up);
end $$;

