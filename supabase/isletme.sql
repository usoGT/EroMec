-- Kullanıcı bilgisi: işletmesiyle birlikte
create or replace function public.me_json() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id', p.id, 'email', p.email, 'fullName', p.full_name, 'role', case when p.workspace_role = 'owner' then 'admin' else 'chief' end,
           'workspaceId', p.workspace_id, 'workspaceRole', p.workspace_role, 'workspaceName', w.name,
           'siteIds', coalesce((select jsonb_agg(m.site_id order by m.site_id) from public.site_members m
                                join public.sites s on s.id = m.site_id where m.user_id = p.id and s.workspace_id = p.workspace_id), '[]'::jsonb))
  from public.profiles p left join public.workspaces w on w.id = p.workspace_id where p.id = auth.uid();
$$;

create or replace function public.pull_all() returns jsonb
language plpgsql security invoker set search_path = public as $$
declare t record; rows jsonb; data jsonb := '{}'; started timestamptz := clock_timestamp();
begin
  if auth.uid() is null then raise exception 'Giriş gerekli' using errcode = '42501'; end if;
  for t in select * from public.sync_tables() order by ord loop
    execute format('select coalesce(jsonb_agg(to_jsonb(x) - ''_changed_at'' - ''workspace_id''), ''[]''::jsonb) from public.%I x', t.tbl) into rows;
    data := data || jsonb_build_object(t.tbl, rows);
  end loop;
  return jsonb_build_object('data', data, 'me', public.me_json(), 'ids', public.reserve_ids(), 'serverTime', started);
end $$;

create or replace function public.pull_since(since timestamptz) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare t record; rows jsonb; data jsonb := '{}'; dels jsonb; started timestamptz := clock_timestamp();
begin
  if auth.uid() is null then raise exception 'Giriş gerekli' using errcode = '42501'; end if;
  if since is null or since < now() - interval '80 days' then
    raise exception 'Çok eski; baştan indirilmeli' using errcode = '22023';
  end if;
  for t in select * from public.sync_tables() order by ord loop
    execute format('select coalesce(jsonb_agg(to_jsonb(x) - ''_changed_at'' - ''workspace_id''), ''[]''::jsonb) from public.%I x where x._changed_at > $1', t.tbl)
      into rows using since;
    if jsonb_array_length(rows) > 0 then data := data || jsonb_build_object(t.tbl, rows); end if;
  end loop;
  select coalesce(jsonb_agg(jsonb_build_object('t', d.tbl, 'pk', d.pk) order by d.id), '[]'::jsonb)
    into dels from public.sync_deletes d where d.deleted_at > since;
  return jsonb_build_object('data', data, 'deletes', dels, 'me', public.me_json(), 'serverTime', started);
end $$;

