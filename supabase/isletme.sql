-- Ayar anahtarı ve fırça kodu işletme başına benzersiz
do $$
declare fk text;
begin
  if (select count(*) from information_schema.key_column_usage k join information_schema.table_constraints c using (constraint_name, table_schema)
      where c.table_schema = 'public' and c.table_name = 'settings' and c.constraint_type = 'PRIMARY KEY') = 1 then
    alter table public.settings drop constraint settings_pkey;
    alter table public.settings add constraint settings_pkey primary key (workspace_id, key);
  end if;
  if (select count(*) from information_schema.key_column_usage k join information_schema.table_constraints c using (constraint_name, table_schema)
      where c.table_schema = 'public' and c.table_name = 'attendance_statuses' and c.constraint_type = 'PRIMARY KEY') = 1 then
    select conname into fk from pg_constraint where conrelid = 'public.attendance'::regclass and contype = 'f'
      and confrelid = 'public.attendance_statuses'::regclass;
    if fk is not null then execute format('alter table public.attendance drop constraint %I', fk); end if;
    alter table public.attendance_statuses drop constraint attendance_statuses_pkey;
    alter table public.attendance_statuses add constraint attendance_statuses_pkey primary key (workspace_id, code);
    alter table public.attendance add constraint attendance_status_fkey foreign key (workspace_id, status)
      references public.attendance_statuses (workspace_id, code) on delete restrict on update cascade deferrable initially immediate;
  end if;
end $$;
