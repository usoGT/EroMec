declare t record;
begin
  for t in select tbl from public.sync_tables() loop
    execute format('alter table public.%I add column if not exists workspace_id bigint default public.my_workspace() references public.workspaces(id) on delete cascade', t.tbl);
    execute format('create index if not exists ix_%s_workspace on public.%I (workspace_id)', t.tbl, t.tbl);
  end loop;
end $$;
