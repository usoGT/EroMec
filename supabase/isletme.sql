create or replace function public.can_access_site(sid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select (public.is_admin() and (sid is null or exists (select 1 from public.sites where id = sid and workspace_id = public.my_workspace())))
      or (sid is not null and exists (select 1 from public.site_members m join public.sites s on s.id = m.site_id
                                      where m.user_id = auth.uid() and m.site_id = sid and s.workspace_id = public.my_workspace()));
$$;

create or replace function public.in_my_workspace(ws bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select ws is not null and ws = public.my_workspace();
$$;

do $$
declare t record;
begin
  for t in select * from (values ('employees', 'employees_all'), ('overtime_records', 'overtime_all'), ('expenses', 'expenses_all'),
                                 ('attendance', 'attendance_all'), ('payrolls', 'payrolls_all'), ('daily_reports', 'daily_reports_all')) v(tbl, pol) loop
    execute format('drop policy if exists %I on public.%I', t.pol, t.tbl);
    execute format('create policy %I on public.%I for all to authenticated using (public.in_my_workspace(workspace_id) and public.can_access_row(site_id, owner_id)) with check (public.in_my_workspace(workspace_id) and public.can_access_row(site_id, owner_id))', t.pol, t.tbl);
  end loop;
end $$;

