-- Puanto işletmeleri (artimli.sql'den SONRA çalıştırılır; tekrar çalıştırmak güvenlidir).
-- Her işletme (firma) kendi ayrı alanıdır: firma listesi, ayarlar, gider kategorileri, puantaj fırçaları,
-- şantiyeler ve bütün kayıtlar işletmeye aittir; başka işletme hiçbirini göremez.
--   * Kayıt olan kişi ya kendi işletmesini açar (sahip olur) ya da bir işletme sahibi onu e-postasıyla ekler.
--   * Bir kişi aynı anda tek işletmededir.
--   * İşletme sahibi kendi işletmesindeki her şeyi görür. Üyeler, eskisi gibi kendi açtıkları ve kendileriyle
--     paylaşılan şantiyeleri görür; firma, ayar, kategori ve fırçalar işletme içinde ortaktır.
--   * Varsayılan listeler (workspace_id boş satırlar) yeni işletmeye kopyalanan şablondur; kimse doğrudan görmez.

create table if not exists public.workspaces (
  id         bigint generated by default as identity primary key,
  name       text not null check (length(trim(name)) > 0),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.workspaces enable row level security;

alter table public.profiles add column if not exists workspace_id bigint references public.workspaces(id) on delete set null;
alter table public.profiles add column if not exists workspace_role text not null default 'member' check (workspace_role in ('owner', 'member'));
create index if not exists ix_profiles_workspace on public.profiles (workspace_id);

-- Kayıt olmadan önce eklenen kişiler: kayıt olunca işletmeye otomatik katılır.
create table if not exists public.workspace_invites (
  email        text   not null,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  created_at   timestamptz not null default now(),
  primary key (email, workspace_id)
);
alter table public.workspace_invites enable row level security;

create or replace function public.my_workspace() returns bigint
language sql stable security definer set search_path = public as $$
  select workspace_id from public.profiles where id = auth.uid();
$$;

-- "Yönetici" artık işletme sahibidir (yalnızca kendi işletmesinde, aşağıdaki politikalar işletmeyle sınırlar).
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and workspace_id is not null and workspace_role = 'owner');
$$;

drop policy if exists workspaces_read on public.workspaces;
create policy workspaces_read on public.workspaces for select to authenticated using (id = public.my_workspace());

